"""Archive the restored F3 package graph and its original licence/notice texts.

Uses only stdlib and existing NuGet assets. Does not restore or install packages.
Remote fallback reads exact repository commits from restored package metadata.
"""
import hashlib
import json
from pathlib import Path, PurePosixPath
import urllib.error
import urllib.request
import xml.etree.ElementTree as ET

REPO = Path(__file__).resolve().parents[2]
OUTPUT = REPO / 'docs/third-party/avalonia-f3'
PROJECTS = ['src/MZTools.Desktop', 'tests/MZTools.Desktop.Tests']
cache = {}

def archive(data):
    digest = hashlib.sha256(data).hexdigest()
    path = OUTPUT / 'licenses' / (digest + '.txt')
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    return {'file': 'licenses/' + path.name, 'sha256': digest}

def remote_text(url):
    if url not in cache:
        try:
            with urllib.request.urlopen(url, timeout=20) as response:
                cache[url] = response.read()
        except urllib.error.HTTPError as error:
            if error.code != 404:
                raise
            cache[url] = None
    return cache[url]

def main():
    packages = {}
    for project in PROJECTS:
        assets = json.loads((REPO / project / 'obj/project.assets.json').read_text(encoding='utf-8-sig'))
        folders = [Path(p) for p in assets['packageFolders']]
        for key, library in assets['libraries'].items():
            if library['type'] != 'package':
                continue
            if key in packages:
                packages[key]['projects'].append(project)
                continue
            directory = next(p / library['path'] for p in folders if (p / library['path']).exists())
            root = ET.parse(next(directory.glob('*.nuspec'))).getroot()
            meta = {n.tag.split('}')[-1]: n for n in list(root)[0]}
            licence = meta.get('license')
            repository = meta.get('repository')
            record = {'package': key, 'projects': [project], 'sha512': library.get('sha512'),
                      'license': licence.text if licence is not None else None,
                      'licenseType': licence.attrib.get('type') if licence is not None else None,
                      'repository': repository.attrib if repository is not None else {},
                      'copyright': meta['copyright'].text if 'copyright' in meta else None, 'texts': []}
            for name in library.get('files', []):
                if any(word in PurePosixPath(name).name.lower() for word in ('license', 'notice', 'copying')):
                    record['texts'].append({'origin': 'NuGet:' + key + '/' + name, **archive((directory / name).read_bytes())})
            if not record['texts'] and repository is not None:
                url = repository.attrib.get('url', '').rstrip('/').removesuffix('.git')
                commit = repository.attrib.get('commit')
                if url.startswith('https://github.com/') and commit:
                    base = url.replace('https://github.com/', 'https://raw.githubusercontent.com/') + '/' + commit + '/'
                    for name in ('LICENSE', 'LICENSE.md', 'LICENSE.txt', 'LICENCE', 'licence.md', 'License.txt', 'COPYING'):
                        data = remote_text(base + name)
                        if data is not None:
                            record['texts'].append({'origin': base + name, **archive(data)})
                            break
            packages[key] = record
    # The Inter font is only brought in by headless tests; archive OFL in addition to the Avalonia wrapper MIT.
    inter_key = next(k for k in packages if k.startswith('Avalonia.Fonts.Inter/'))
    font_url = 'https://raw.githubusercontent.com/rsms/inter/v4.1/LICENSE.txt'
    font = remote_text(font_url)
    if font is not None:
        packages[inter_key]['texts'].append({'origin': font_url, **archive(font)})
    OUTPUT.mkdir(parents=True, exist_ok=True)
    (OUTPUT / 'packages.json').write_text(json.dumps(list(packages.values()), ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    lines = ['# F3 restored third-party packages', '',
             'Generated by `tests/MZTools.Desktop.Smoke/collect_notices.py` from restored assets. Native bundled third-party terms remain in the archived original notices. Test-only packages are not required by the production executable.', '',
             '| Package | Scope | NuGet license | Original texts |', '| --- | --- | --- | --- |']
    for key, p in sorted(packages.items()):
        links = ', '.join(f'[text {i+1}]({t["file"]})' for i,t in enumerate(p['texts'])) or '**No text found; inspect metadata**'
        lines.append(f'| {key} | {"Desktop" if PROJECTS[0] in p["projects"] else "Tests only"} | {p["license"]} | {links} |')
    lines += ['', 'Package content hashes, source commits, original file paths and archived-text SHA-256 values are in [packages.json](packages.json).', '']
    (OUTPUT / 'README.md').write_text('\n'.join(lines), encoding='utf-8')
    missing = [key for key,p in packages.items() if not p['texts']]
    print(f'{len(packages)} packages; {len(list((OUTPUT / "licenses").glob("*.txt")))} distinct archived texts; missing texts: {missing}; Inter OFL found: {font is not None}')

if __name__ == '__main__':
    main()
