"""Generate/check Avalonia resources from the approved canonical F2 tokens."""
import argparse
import json
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT.parents[1] / 'src/MZTools.Desktop/Theme/Tokens.axaml'

def render():
    tokens = json.loads((ROOT / 'tokens.json').read_text(encoding='utf-8'))
    lines = ['<!-- Generated by build_avalonia_tokens.py; edit canonical tokens.json. -->',
             '<ResourceDictionary xmlns="https://github.com/avaloniaui" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">']
    for name, color in tokens['colors'].items():
        # CSS is RGBA; Avalonia is ARGB.
        if len(color) == 9:
            color = '#' + color[7:9] + color[1:7]
        lines.append(f'  <SolidColorBrush x:Key="F2.{name}">{color}</SolidColorBrush>')
    for group in ('typography', 'spacing', 'components'):
        for name, value in tokens[group].items():
            if isinstance(value, (int, float)):
                lines.append(f'  <x:Double x:Key="F2.{group}.{name}">{value}</x:Double>')
    for name in ('controlRadius', 'panelRadius'):
        lines.append(f'  <CornerRadius x:Key="F2.{name}">{tokens["components"][name]}</CornerRadius>')
    lines.append(f'  <Thickness x:Key="F2.panelPadding">{tokens["spacing"]["lg"]}</Thickness>')
    lines.append(f'  <Thickness x:Key="F2.controlPadding">{tokens["spacing"]["md"]},{tokens["spacing"]["xs"]}</Thickness>')
    lines.append(f'  <Thickness x:Key="F2.rowPadding">{tokens["spacing"]["sm"]},{tokens["spacing"]["xs"]}</Thickness>')
    lines.append('</ResourceDictionary>')
    return '\n'.join(lines) + '\n'

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render()
    ET.fromstring(expected)
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding='utf-8') != expected:
            raise SystemExit('Avalonia tokens differ from canonical F2 tokens. Regenerate them.')
        print('Avalonia tokens match all canonical colors and numeric tokens.')
    else:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(expected, encoding='utf-8')
        print('Generated ' + str(TARGET))
