"""Generate the review palette from the single source of truth: tokens.json."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]
if __name__=='__main__':
    tokens=json.loads((ROOT/'tokens.json').read_text(encoding='utf-8'))
    css='/* Generated by tools/build_tokens.py from tokens.json. */\n:root {\n'
    css+=''.join(f'  --{name}: {value};\n' for name,value in tokens['colors'].items())+'}\n'
    (ROOT/'prototype/tokens.css').write_text(css,encoding='utf-8')
    print('Generated shared token palette.')
